function banner(title) {
  return `\n-- ============================================================\n-- ${title}\n-- ============================================================\n\n`;
}

function concatFiles(relPaths, header) {
  let out = `-- ${header}\n-- Generated by scripts/build-bootstrap-sql.mjs — do not edit by hand\n`;
  for (const rel of relPaths) {
    const abs = path.join(root, rel);
    if (!fs.existsSync(abs)) {
      throw new Error(`Missing migration: ${rel}`);
    }
    out += banner(rel);
    out += fs.readFileSync(abs, 'utf8');
    if (!out.endsWith('\n')) out += '\n';
  }
  return out;
}

